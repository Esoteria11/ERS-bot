// ==================== 🔧 ФУНКЦИИ ДЛЯ СОРТИРОВКИ ====================

/**
 * Извлекает базовое название улицы (без префикса) для сортировки
 * "ул. Лебедева" → "лебедева", "Юбилейный пер." → "юбилейный"
 */
fun getBaseStreetName(fullName: String): String {
    return fullName.lowercase()
        .replace(Regex("^(ул\\.?\\s*|улица\\s*|пер\\.?\\s*|переулок\\s*|мкр\\.?\\s*|микрорайон\\s*)"), "")
        .replace(Regex("\\s+пер\\.$"), "")
        .trim()
}

/**
 * Возвращает приоритет префикса: чем меньше число, тем выше приоритет
 * ул. = 1, пер. = 2, мкр./другие = 3
 */
fun getPrefixPriority(fullName: String): Int {
    return when {
        fullName.startsWith("ул.") || fullName.startsWith("улица") -> 1
        fullName.endsWith("пер.") || fullName.startsWith("пер.") -> 2
        else -> 3
    }
}

/**
 * Сортирует список улиц: по алфавиту (игнорируя префикс), затем по приоритету префикса
 */
fun sortStreets(streets: List<String>): List<String> {
    return streets.sortedWith(
        compareBy(
            { getBaseStreetName(it) },      // Сначала по базовому названию
            { getPrefixPriority(it) }        // Потом по приоритету префикса
        )
    )
}
